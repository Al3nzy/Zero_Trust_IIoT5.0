for f in ("trust_trajectories", "trust_theory", "per_class_recall", "shap_faithfulness", "dp_tradeoff", "confusion_matrix"):
    for ext in ("pdf", "png"):
        src = os.path.join(ROOT, "figures", f"{f}.{ext}")
        if os.path.exists(src): shutil.copy(src, PF)
